-- Schema is written to run on both PostgreSQL and H2 (PostgreSQL mode, used for tests).

CREATE TABLE customers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR(100)  NOT NULL,
    last_name   VARCHAR(100)  NOT NULL,
    email       VARCHAR(254)  NOT NULL,
    phone       VARCHAR(20)   NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT        NOT NULL,
    account_number VARCHAR(20)   NOT NULL,
    currency       VARCHAR(3)    NOT NULL,
    balance        NUMERIC(19,2) NOT NULL DEFAULT 0,
    status         VARCHAR(10)   NOT NULL,
    version        BIGINT        NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_accounts_number UNIQUE (account_number),
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT ck_accounts_balance_non_negative CHECK (balance >= 0),
    CONSTRAINT ck_accounts_currency CHECK (currency IN ('USD', 'EUR', 'BYN')),
    CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED'))
);
CREATE INDEX idx_accounts_customer ON accounts (customer_id);

CREATE TABLE cards (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT      NOT NULL,
    masked_number VARCHAR(19) NOT NULL,
    expires_at    DATE        NOT NULL,
    status        VARCHAR(10) NOT NULL,
    version       BIGINT      NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_cards_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT ck_cards_status CHECK (status IN ('ACTIVE', 'BLOCKED'))
);
CREATE INDEX idx_cards_account ON cards (account_id);

CREATE TABLE transfers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(64)   NOT NULL,
    from_account_id BIGINT        NOT NULL,
    to_account_id   BIGINT        NOT NULL,
    amount          NUMERIC(19,2) NOT NULL,
    currency        VARCHAR(3)    NOT NULL,
    description     VARCHAR(140),
    status          VARCHAR(10)   NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_transfers_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_transfers_from FOREIGN KEY (from_account_id) REFERENCES accounts (id),
    CONSTRAINT fk_transfers_to FOREIGN KEY (to_account_id) REFERENCES accounts (id),
    CONSTRAINT ck_transfers_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfers_different_accounts CHECK (from_account_id <> to_account_id),
    CONSTRAINT ck_transfers_status CHECK (status IN ('COMPLETED'))
);
CREATE INDEX idx_transfers_from ON transfers (from_account_id);
CREATE INDEX idx_transfers_to ON transfers (to_account_id);

-- Ledger: every balance change is one immutable row.
CREATE TABLE ledger_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT        NOT NULL,
    transfer_id   BIGINT,
    direction     VARCHAR(6)    NOT NULL,
    operation     VARCHAR(10)   NOT NULL,
    amount        NUMERIC(19,2) NOT NULL,
    balance_after NUMERIC(19,2) NOT NULL,
    currency      VARCHAR(3)    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ledger_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT fk_ledger_transfer FOREIGN KEY (transfer_id) REFERENCES transfers (id),
    CONSTRAINT ck_ledger_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_ledger_balance_non_negative CHECK (balance_after >= 0),
    CONSTRAINT ck_ledger_direction CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ck_ledger_operation CHECK (operation IN ('TRANSFER', 'DEPOSIT'))
);
CREATE INDEX idx_ledger_account_created ON ledger_entries (account_id, id DESC);
CREATE INDEX idx_ledger_transfer ON ledger_entries (transfer_id);
